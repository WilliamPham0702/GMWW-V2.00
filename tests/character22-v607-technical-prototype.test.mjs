import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {buildCharacter22Prototype,BONES,ACTIONS,OUTPUT} from '../scripts/build-character22-v607-technical-rig.mjs';
import {parseGlb} from '../scripts/vendor-character21-v605.mjs';
test('Character 22 has an independent real volumetric GLB with sixteen joints/four clips, not a copy of Character 21',async()=>{
 const result=await buildCharacter22Prototype();
 const glb=readFileSync(OUTPUT),accepted=readFileSync('assets/characters/overhaul-v600/character-21/skin.glb');
 assert.equal(glb.toString('ascii',0,4),'glTF');
 assert.equal(glb.readUInt32LE(4),2);
 assert.equal(glb.readUInt32LE(8),glb.length);
 assert.notEqual(createHash('sha256').update(glb).digest('hex'),createHash('sha256').update(accepted).digest('hex'));
 const {json,bin}=parseGlb(glb);
 assert.equal(json.extras.characterId,'character-22');
 assert.equal(json.extras.status,'TECHNICAL_PROTOTYPE_NOT_APPROVED_ART');
 assert.equal(json.extras.geometry,'volumetric-3d');
 assert.equal(json.extras.cameraAngles,8);
 assert.equal(json.extras.artDirectionsApproved,1);
 assert.equal(json.extras.productionEnabled,false);
 assert.equal(json.extras.mainEnabled,false);
 assert.equal(json.extras.stagingOnly,true);
 assert.equal(json.skins[0].joints.length,16);
 assert.deepEqual(json.skins[0].joints.map(i=>json.nodes[i].name),BONES);
 assert.deepEqual(json.animations.map(a=>a.name),ACTIONS);
 assert.ok(json.meshes[0].primitives[0].attributes.JOINTS_0!==undefined);
 assert.ok(json.meshes[0].primitives[0].attributes.WEIGHTS_0!==undefined);
 assert.ok(bin.length>1000&&glb.length>20000);
 assert.equal(result.ownerApproved,false);
 assert.equal(result.finalSkin,false);
});
test('Technical-only 3D review uses different filename from owner-accepted artwork and live catalog',()=>{
 const page=readFileSync('assets/character-v605-review/character22-technical.html','utf8');
 assert.ok(page.includes('/characters/overhaul-v600/character-22/technical-prototype.glb'));
 assert.ok(page.includes('/characters/overhaul-v600/character-22/avatar.webp'));
 assert.ok(page.includes('KHÔNG PHẢI'));
 assert.ok(page.includes('id="directions"')&&page.includes('id="actions"'));
 const roster=JSON.parse(readFileSync('assets/characters/overhaul-v600/portraits-22-30-v606-staging.json','utf8'));
 assert.equal(roster.characters[0].availableGLB,false,'prototype must not be promoted as approved rig');
 assert.equal(roster.characters[0].validArtworkViews,1);
});
